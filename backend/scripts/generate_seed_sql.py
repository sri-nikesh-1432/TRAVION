"""Generate database/seed.sql — the OPTIONAL MySQL development seed.

Run from backend/:  python scripts/generate_seed_sql.py

What it emits (and ONLY this):
  * the 15 verified locations from app.services.verified_data.VERIFIED_LOCATIONS
    (the exact rows the app itself seeds at startup when the table is empty);
  * the documented demo staff logins (manager@travion.in / admin@travion.in)
    and the pre-provisioned Ooty guide (arun.nilgiri@travion.in) with
    freshly-salted bcrypt hashes for their documented passwords.

It deliberately emits NO trips, payments, reviews, itineraries or analytics —
fabricated financial rows would poison the dashboards and the test data. The
seed is idempotent (INSERT IGNORE keyed on primary keys / emails), so running
it twice, or running it before the app's own startup seeding, produces the
same database. The app's startup seeding detects existing rows and skips.
"""
from __future__ import annotations

import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.core.security import get_password_hash  # noqa: E402
from app.services.verified_data import VERIFIED_LOCATIONS  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "database" / "seed.sql"

# Deterministic UUIDs so re-running the seed (or comparing two databases)
# produces identical identity rows. Only ever used for these seed records.
STAFF = [
    # (identity_id, role_row_id, email, password, role, name)
    ("00000000-0000-4000-8000-00000000ad01", "00000000-0000-4000-8000-00000000ad02",
     "admin@travion.in", "adminpassword", "ADMIN", "Platform Administrator"),
    ("00000000-0000-4000-8000-00000000mn01", "00000000-0000-4000-8000-00000000mn02",
     "manager@travion.in", "managerpassword", "MANAGER", "Operations Manager"),
]
GUIDE = {
    "identity_id": "00000000-0000-4000-8000-00000000gd01",
    "guide_id": "00000000-0000-4000-8000-00000000gd02",
    "email": "arun.nilgiri@travion.in",
    "password": "guide1234",
}


def q(value) -> str:
    """SQL string literal with proper escaping for MySQL (utf8mb4)."""
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return repr(value)
    text = str(value).replace("\\", "\\\\").replace("'", "''")
    return f"'{text}'"


def j(value) -> str:
    """JSON column literal (SQLAlchemy JSON columns store serialised JSON)."""
    if value is None:
        return "NULL"
    import json
    return q(json.dumps(value, ensure_ascii=False))


def main() -> None:
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines: list[str] = [
        "-- =====================================================================",
        "-- TRAVION — OPTIONAL MySQL development seed",
        f"-- Generated by backend/scripts/generate_seed_sql.py at {generated}",
        "--",
        "-- Contains ONLY reference data the app itself would seed at startup:",
        "--   * 15 verified locations (verbatim from VERIFIED_LOCATIONS)",
        "--   * demo Manager / Admin logins + the pre-provisioned Ooty guide",
        "-- NO trips, payments, reviews, itineraries or analytics are faked here",
        "-- (fabricated financial rows would poison dashboards and test data).",
        "--",
        "-- Idempotent: every statement is INSERT IGNORE — safe to run repeatedly,",
        "-- before or after the app has booted once (startup seeding skips rows",
        "-- that already exist).",
        "--",
        "-- Workbench: open this file, make sure the editor is bound to the",
        "-- travion_db schema (schema tab), then Execute (lightning bolt).",
        "-- =====================================================================",
        "USE travion_db;",
        "SET NAMES utf8mb4;",
        "SET FOREIGN_KEY_CHECKS = 0;  -- parents below are inserted in FK order anyway",
        "",
    ]

    # ── locations (parents of everything trip-related) ──────────────────────
    lines.append("-- ── Verified locations ──────────────────────────────────────────────")
    for loc in VERIFIED_LOCATIONS:
        cols = (
            "id, name, state, country, lat, lng, place_id, description, "
            "hero_image, popular_season"
        )
        vals = ", ".join([
            q(loc["id"]), q(loc["name"]), q(loc["state"]), q(loc.get("country", "India")),
            q(loc["lat"]), q(loc["lng"]), q(loc.get("place_id")),
            q(loc.get("description")), q(loc.get("hero_image")),
            q(loc.get("popular_season")),
        ])
        lines.append(f"INSERT IGNORE INTO locations ({cols}) VALUES ({vals});")
    lines.append("")

    # ── demo staff ─────────────────────────────────────────────────────────
    lines.append("-- ── Demo Manager / Admin (documented README credentials) ───────────")
    for identity_id, role_row_id, email, password, role, name in STAFF:
        pwd = get_password_hash(password)  # fresh bcrypt salt each generation
        lines.append(
            "INSERT IGNORE INTO identities (id, email, hashed_password, role) "
            f"VALUES ({q(identity_id)}, {q(email)}, {q(pwd)}, {q(role)});"
        )
        table = "managers" if role == "MANAGER" else "admins"
        lines.append(
            f"INSERT IGNORE INTO {table} (id, identity_id, name) VALUES "
            f"({q(role_row_id)}, {q(identity_id)}, {q(name)});"
        )
    lines.append("")

    # ── pre-provisioned guide ──────────────────────────────────────────────
    lines.append("-- ── Pre-provisioned Ooty guide (demo login) ────────────────────────")
    pwd = get_password_hash(GUIDE["password"])
    lines.append(
        "INSERT IGNORE INTO identities (id, email, hashed_password, role) "
        f"VALUES ({q(GUIDE['identity_id'])}, {q(GUIDE['email'])}, {q(pwd)}, 'GUIDE');"
    )
    guide_cols = (
        "id, identity_id, first_name, last_name, photo_url, phone, status, "
        "approval_status, languages, destinations, experience_years, "
        "specializations, destination_knowledge, safety_information, "
        "rating, review_count"
    )
    guide_vals = ", ".join([
        q(GUIDE["guide_id"]), q(GUIDE["identity_id"]),
        q("Arun"), q("Kumar"),
        q("https://images.unsplash.com/photo-1507003211169-0a1dd7228f2d"
          "?auto=format&fit=crop&w=400&q=80"),
        q("+91 98421 88410"), q("ACTIVE"), q("APPROVED"),
        j(["English", "Tamil", "Hindi"]),
        j(["Ooty", "Coimbatore", "Munnar"]),
        q(8),
        j(["Trekking", "Tea History", "Wildlife Photography"]),
        q("Born and raised in the Nilgiris. Expert on Toda tribal heritage "
          "trails, Shola forests, and secret viewpoint spots away from tourists."),
        q("Always carry woollens after 5 PM. Kalhatty ghat road requires "
          "experienced low-gear driving. High altitude acclimatization advisory."),
        q(4.9), q(34),
    ])
    lines.append(
        f"INSERT IGNORE INTO guides ({guide_cols}) VALUES ({guide_vals});"
    )
    lines.append("")
    lines.append("SET FOREIGN_KEY_CHECKS = 1;")
    lines.append("")
    lines.append("-- Verify:")
    lines.append("--   SELECT (SELECT COUNT(*) FROM locations) AS locations,")
    lines.append("--          (SELECT COUNT(*) FROM identities) AS identities,")
    lines.append("--          (SELECT COUNT(*) FROM guides) AS guides;")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(lines)} lines, {OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
